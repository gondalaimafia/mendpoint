function toLearningCase(seed: CaseSeed): LearningCase {
  const sourceId = `${seed.id.toLowerCase()}-source-1`;
  const source = sourceLibrary[seed.source];
  const repository = repositories[seed.repository];
  const numericId = Number(seed.id.slice(-3));

  return {
    schemaVersion: "mendpoint.learning-case.v1",
    id: seed.id,
    product: "fettler",
    cohort: seed.id.startsWith("FET-C") ? "common" : "edge",
    datasetSplit: numericId % 5 === 0 ? "holdout" : "development",
    title: seed.title,
    importance: {
      statement: seed.importance,
      frequencyClaim: "not_claimed",
      sourceIds: [sourceId],
    },
    sources: [{ id: sourceId, ...source, retrievedAt: RETRIEVED_AT }],
    repository: {
      provenanceId: repository.provenanceId,
      languages: [...repository.languages],
      frameworks: [...repository.frameworks],
    },
    pattern: {
      family: seed.family,
      seededFailure: seed.seededFailure,
      expectedImpactGraph: seed.impact,
      evidenceState: seed.evidenceState ?? "verified",
    },
    expected: {
      diagnosis: seed.diagnosis,
      repairOrMigration: seed.repair,
      oracleIds: [seed.oracle],
      productionAcceptance: seed.acceptance,
    },
    fixture: {
      manifestId: `fixture-${seed.id.toLowerCase()}-manifest-v1`,
      mutationId: `mutation-${seed.id.toLowerCase()}-seed-v1`,
      allowedEditPaths: seed.allowedEditPaths,
      rollbackId: `rollback-${seed.id.toLowerCase()}-restore-pristine-v1`,
      cleanupId: `cleanup-${seed.id.toLowerCase()}-sandbox-v1`,
    },
    security: {
      tenantRisk: seed.tenantRisk,
      risks: seed.risks,
      requiresDedicatedBenchmarkTenant: true,
    },
  };
}

export const fettlerCases: LearningCase[] = seeds.map(toLearningCase);
